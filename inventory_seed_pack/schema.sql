-- Department-aware current inventory view. Overdue is a subset of outstanding issued quantity.
CREATE VIEW v_inventory_summary AS
WITH asset_counts AS (
  SELECT department_id, inventory_item_id,
         COUNT(*)::INTEGER AS total_quantity,
         COUNT(*) FILTER (WHERE status='AVAILABLE')::INTEGER AS available_quantity,
         COUNT(*) FILTER (WHERE status='ISSUED')::INTEGER AS issued_quantity,
         COUNT(*) FILTER (WHERE status='DAMAGED')::INTEGER AS damaged_quantity,
         COUNT(*) FILTER (WHERE status='LOST')::INTEGER AS lost_quantity,
         COUNT(*) FILTER (WHERE status='MAINTENANCE')::INTEGER AS maintenance_quantity,
         COUNT(*) FILTER (WHERE status='RETIRED')::INTEGER AS retired_quantity
  FROM assets GROUP BY department_id, inventory_item_id
), overdue_counts AS (
  SELECT department_id, inventory_item_id,
         COALESCE(SUM(outstanding_quantity) FILTER (WHERE due_date < CURRENT_DATE),0)::INTEGER AS overdue_quantity
  FROM issue_lines WHERE outstanding_quantity > 0 GROUP BY department_id, inventory_item_id
)
SELECT i.id AS inventory_item_id, i.department_id, d.name AS department_name, i.item_code, i.name AS item_name,
       i.category, i.tracking_type,
       CASE WHEN i.tracking_type='QUANTITY' THEN q.total_quantity ELSE COALESCE(a.total_quantity,0) END AS total_quantity,
       CASE WHEN i.tracking_type='QUANTITY' THEN q.available_quantity ELSE COALESCE(a.available_quantity,0) END AS available_quantity,
       CASE WHEN i.tracking_type='QUANTITY' THEN q.issued_quantity ELSE COALESCE(a.issued_quantity,0) END AS issued_quantity,
       CASE WHEN i.tracking_type='QUANTITY' THEN q.damaged_quantity ELSE COALESCE(a.damaged_quantity,0) END AS damaged_quantity,
       CASE WHEN i.tracking_type='QUANTITY' THEN q.lost_quantity ELSE COALESCE(a.lost_quantity,0) END AS lost_quantity,
       CASE WHEN i.tracking_type='QUANTITY' THEN q.maintenance_quantity ELSE COALESCE(a.maintenance_quantity,0) END AS maintenance_quantity,
       CASE WHEN i.tracking_type='QUANTITY' THEN q.retired_quantity ELSE COALESCE(a.retired_quantity,0) END AS retired_quantity,
       COALESCE(o.overdue_quantity,0) AS overdue_quantity
FROM inventory_items i
JOIN departments d ON d.id=i.department_id
LEFT JOIN quantity_stock q ON q.item_id=i.id
LEFT JOIN asset_counts a ON a.inventory_item_id=i.id AND a.department_id=i.department_id
LEFT JOIN overdue_counts o ON o.inventory_item_id=i.id AND o.department_id=i.department_id;

CREATE VIEW v_overdue_issues AS
SELECT il.id AS issue_line_id, il.department_id, d.name AS department_name,
       sp.enrolment_number, u.full_name AS student_name, i.item_code, i.name AS item_name,
       il.quantity_issued, il.quantity_returned, il.outstanding_quantity, il.due_date,
       (CURRENT_DATE - il.due_date) AS overdue_days, iss.id AS issue_id
FROM issue_lines il
JOIN issues iss ON iss.id=il.issue_id AND iss.department_id=il.department_id
JOIN student_profiles sp ON sp.id=iss.student_id AND sp.department_id=iss.department_id
JOIN users u ON u.id=sp.user_id
JOIN inventory_items i ON i.id=il.inventory_item_id AND i.department_id=il.department_id
JOIN departments d ON d.id=il.department_id
WHERE il.outstanding_quantity > 0 AND il.due_date < CURRENT_DATE;

CREATE VIEW v_upcoming_due_issues AS
SELECT il.id AS issue_line_id, il.department_id, d.name AS department_name,
       sp.enrolment_number, u.full_name AS student_name, i.item_code, i.name AS item_name,
       il.outstanding_quantity, il.due_date, (il.due_date - CURRENT_DATE) AS days_until_due,
       iss.id AS issue_id
FROM issue_lines il
JOIN issues iss ON iss.id=il.issue_id AND iss.department_id=il.department_id
JOIN student_profiles sp ON sp.id=iss.student_id AND sp.department_id=iss.department_id
JOIN users u ON u.id=sp.user_id
JOIN inventory_items i ON i.id=il.inventory_item_id AND i.department_id=il.department_id
JOIN departments d ON d.id=il.department_id
WHERE il.outstanding_quantity > 0 AND il.due_date >= CURRENT_DATE AND il.due_date <= CURRENT_DATE + 7;

