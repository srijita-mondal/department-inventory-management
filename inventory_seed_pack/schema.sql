-- Department Inventory and Student Item Issue Management System
-- PostgreSQL 14+ recommended. Run schema.sql first, then seed.sql.
BEGIN;

CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(6) NOT NULL UNIQUE CHECK (code ~ '^[0-9]{6}$'),
    short_code VARCHAR(12) NOT NULL UNIQUE CHECK (short_code ~ '^[A-Z0-9]+$'),
    name VARCHAR(120) NOT NULL UNIQUE CHECK (char_length(btrim(name)) BETWEEN 2 AND 120),
    status VARCHAR(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL CHECK (char_length(btrim(full_name)) BETWEEN 2 AND 120),
    email VARCHAR(254) NOT NULL,
    password_hash TEXT,
    auth_provider VARCHAR(12) NOT NULL DEFAULT 'LOCAL' CHECK (auth_provider IN ('LOCAL','OIDC')),
    account_status VARCHAR(20) NOT NULL DEFAULT 'PENDING_ACTIVATION' CHECK (account_status IN ('PENDING_ACTIVATION','ACTIVE','SUSPENDED','DISABLED')),
    email_verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (account_status <> 'ACTIVE' OR auth_provider = 'OIDC' OR password_hash IS NOT NULL)
);
CREATE UNIQUE INDEX users_email_ci_uq ON users (lower(btrim(email)));

CREATE TABLE student_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
    enrolment_number VARCHAR(12) NOT NULL UNIQUE CHECK (enrolment_number ~ '^[0-9]{12}$'),
    admission_year SMALLINT NOT NULL CHECK (admission_year BETWEEN 2000 AND 2099),
    course_code CHAR(2) NOT NULL CHECK (course_code ~ '^[0-9]{2}$'),
    roll_number SMALLINT NOT NULL CHECK (roll_number BETWEEN 1 AND 99),
    programme VARCHAR(120) NOT NULL CHECK (char_length(btrim(programme)) BETWEEN 2 AND 120),
    semester SMALLINT NOT NULL CHECK (semester BETWEEN 1 AND 20),
    contact_phone VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (department_id, admission_year, course_code, roll_number),
    UNIQUE (id, department_id),
    CHECK (contact_phone IS NULL OR char_length(btrim(contact_phone)) BETWEEN 7 AND 30)
);

CREATE FUNCTION validate_student_enrolment_number() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE dept_code VARCHAR(6);
BEGIN
    SELECT code INTO dept_code FROM departments WHERE id = NEW.department_id;
    IF dept_code IS NULL THEN
        RAISE EXCEPTION 'Unknown department for student profile';
    END IF;
    IF substring(NEW.enrolment_number FROM 1 FOR 2) <> right(NEW.admission_year::text, 2)
       OR substring(NEW.enrolment_number FROM 3 FOR 6) <> dept_code
       OR substring(NEW.enrolment_number FROM 9 FOR 2) <> NEW.course_code
       OR substring(NEW.enrolment_number FROM 11 FOR 2) <> lpad(NEW.roll_number::text, 2, '0') THEN
        RAISE EXCEPTION 'Enrolment number must be YY + six-digit department code + two-digit course code + two-digit roll number';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER student_enrolment_format_trg BEFORE INSERT OR UPDATE OF enrolment_number, department_id, admission_year, course_code, roll_number
ON student_profiles FOR EACH ROW EXECUTE FUNCTION validate_student_enrolment_number();

CREATE TABLE department_memberships (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
    membership_type VARCHAR(12) NOT NULL CHECK (membership_type IN ('STUDENT','STAFF')),
    status VARCHAR(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, department_id)
);

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE CHECK (code ~ '^[A-Z][A-Z0-9_]+$'),
    name VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(80) NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9._]+$'),
    description VARCHAR(240) NOT NULL
);
CREATE TABLE role_permissions (
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);
CREATE TABLE role_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    department_id BIGINT REFERENCES departments(id) ON DELETE RESTRICT,
    assigned_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX role_assignments_scope_uq ON role_assignments (user_id, role_id, COALESCE(department_id, 0));
CREATE INDEX role_assignments_user_idx ON role_assignments (user_id);

CREATE TABLE storage_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
    location_code VARCHAR(32) NOT NULL CHECK (location_code ~ '^[A-Z0-9-]{3,32}$'),
    name VARCHAR(120) NOT NULL CHECK (char_length(btrim(name)) BETWEEN 2 AND 120),
    location_type VARCHAR(20) NOT NULL CHECK (location_type IN ('DEPARTMENT','LAB','ROOM','CUPBOARD','STORE','MAINTENANCE','OTHER')),
    status VARCHAR(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    UNIQUE (department_id, location_code),
    UNIQUE (id, department_id)
);
CREATE UNIQUE INDEX storage_location_name_ci_uq ON storage_locations (department_id, lower(btrim(name)));

CREATE TABLE inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
    item_code VARCHAR(32) NOT NULL CHECK (item_code ~ '^[A-Z0-9]+(-[A-Z0-9]+){1,3}$' AND char_length(item_code) BETWEEN 6 AND 32),
    name VARCHAR(120) NOT NULL CHECK (char_length(btrim(name)) BETWEEN 2 AND 120),
    category VARCHAR(80) NOT NULL CHECK (char_length(btrim(category)) BETWEEN 2 AND 80),
    description TEXT NOT NULL CHECK (char_length(btrim(description)) BETWEEN 5 AND 1000),
    make_model VARCHAR(120),
    tracking_type VARCHAR(12) NOT NULL CHECK (tracking_type IN ('INDIVIDUAL','QUANTITY')),
    unit VARCHAR(24) NOT NULL DEFAULT 'piece' CHECK (char_length(btrim(unit)) BETWEEN 1 AND 24),
    status VARCHAR(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','RETIRED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (department_id, item_code),
    UNIQUE (id, department_id)
);
CREATE UNIQUE INDEX inventory_item_name_model_ci_uq ON inventory_items
  (department_id, lower(btrim(name)), lower(COALESCE(btrim(make_model), '')));
CREATE INDEX inventory_items_department_idx ON inventory_items (department_id, status);

CREATE TABLE quantity_stock (
    item_id BIGINT PRIMARY KEY,
    department_id BIGINT NOT NULL,
    total_quantity INTEGER NOT NULL CHECK (total_quantity >= 0),
    available_quantity INTEGER NOT NULL CHECK (available_quantity >= 0),
    issued_quantity INTEGER NOT NULL CHECK (issued_quantity >= 0),
    damaged_quantity INTEGER NOT NULL CHECK (damaged_quantity >= 0),
    lost_quantity INTEGER NOT NULL CHECK (lost_quantity >= 0),
    maintenance_quantity INTEGER NOT NULL CHECK (maintenance_quantity >= 0),
    retired_quantity INTEGER NOT NULL CHECK (retired_quantity >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (item_id, department_id) REFERENCES inventory_items(id, department_id) ON DELETE RESTRICT,
    CHECK (total_quantity = available_quantity + issued_quantity + damaged_quantity + lost_quantity + maintenance_quantity + retired_quantity)
);

CREATE TABLE assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL,
    inventory_item_id BIGINT NOT NULL,
    asset_tag VARCHAR(32) NOT NULL UNIQUE CHECK (asset_tag ~ '^[A-Z0-9]+(-[A-Z0-9]+){1,3}$' AND char_length(asset_tag) BETWEEN 6 AND 32),
    serial_number VARCHAR(100),
    location_id BIGINT NOT NULL,
    current_condition VARCHAR(12) NOT NULL DEFAULT 'GOOD' CHECK (current_condition IN ('GOOD','FAIR','DAMAGED','UNKNOWN')),
    status VARCHAR(14) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','ISSUED','DAMAGED','LOST','MAINTENANCE','RETIRED')),
    acquired_date DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (inventory_item_id, department_id) REFERENCES inventory_items(id, department_id) ON DELETE RESTRICT,
    FOREIGN KEY (location_id, department_id) REFERENCES storage_locations(id, department_id) ON DELETE RESTRICT,
    UNIQUE (id, department_id, inventory_item_id),
    CHECK (serial_number IS NULL OR char_length(btrim(serial_number)) BETWEEN 2 AND 100),
    CHECK (status <> 'DAMAGED' OR current_condition = 'DAMAGED')
);
CREATE UNIQUE INDEX assets_serial_ci_uq ON assets (lower(btrim(serial_number))) WHERE serial_number IS NOT NULL AND btrim(serial_number) <> '';
CREATE INDEX assets_department_status_idx ON assets (department_id, status);

CREATE FUNCTION validate_quantity_stock_type() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE item_type VARCHAR(12);
BEGIN
    SELECT tracking_type INTO item_type FROM inventory_items WHERE id = NEW.item_id AND department_id = NEW.department_id;
    IF item_type IS DISTINCT FROM 'QUANTITY' THEN
        RAISE EXCEPTION 'quantity_stock rows are allowed only for QUANTITY-tracked inventory items';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER quantity_stock_type_trg BEFORE INSERT OR UPDATE ON quantity_stock
FOR EACH ROW EXECUTE FUNCTION validate_quantity_stock_type();

CREATE FUNCTION validate_asset_tracking_type() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE item_type VARCHAR(12);
BEGIN
    SELECT tracking_type INTO item_type FROM inventory_items WHERE id = NEW.inventory_item_id AND department_id = NEW.department_id;
    IF item_type IS DISTINCT FROM 'INDIVIDUAL' THEN
        RAISE EXCEPTION 'assets rows are allowed only for INDIVIDUAL-tracked inventory items';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER assets_tracking_type_trg BEFORE INSERT OR UPDATE ON assets
FOR EACH ROW EXECUTE FUNCTION validate_asset_tracking_type();

CREATE TABLE department_policies (
    department_id BIGINT PRIMARY KEY REFERENCES departments(id) ON DELETE RESTRICT,
    max_units_per_student INTEGER NOT NULL DEFAULT 10 CHECK (max_units_per_student BETWEEN 1 AND 1000),
    max_renewals_per_issue INTEGER NOT NULL DEFAULT 2 CHECK (max_renewals_per_issue BETWEEN 0 AND 20),
    renewal_request_before_due_days INTEGER NOT NULL DEFAULT 0 CHECK (renewal_request_before_due_days BETWEEN 0 AND 30),
    allow_overdue_renewal BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
    student_id BIGINT NOT NULL,
    issued_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    purpose VARCHAR(500) NOT NULL CHECK (char_length(btrim(purpose)) BETWEEN 3 AND 500),
    status VARCHAR(12) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED','CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (student_id, department_id) REFERENCES student_profiles(id, department_id) ON DELETE RESTRICT,
    UNIQUE (id, department_id)
);

CREATE TABLE issue_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    inventory_item_id BIGINT NOT NULL,
    asset_id BIGINT,
    issue_date DATE NOT NULL,
    quantity_issued INTEGER NOT NULL CHECK (quantity_issued > 0),
    quantity_returned INTEGER NOT NULL DEFAULT 0 CHECK (quantity_returned >= 0 AND quantity_returned <= quantity_issued),
    outstanding_quantity INTEGER GENERATED ALWAYS AS (quantity_issued - quantity_returned) STORED,
    due_date DATE NOT NULL,
    renewal_count INTEGER NOT NULL DEFAULT 0 CHECK (renewal_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (issue_id, department_id) REFERENCES issues(id, department_id) ON DELETE RESTRICT,
    FOREIGN KEY (inventory_item_id, department_id) REFERENCES inventory_items(id, department_id) ON DELETE RESTRICT,
    FOREIGN KEY (asset_id, department_id, inventory_item_id) REFERENCES assets(id, department_id, inventory_item_id) ON DELETE RESTRICT,
    CHECK (due_date >= issue_date + 15 AND ((due_date - issue_date) % 15) = 0),
    CHECK (asset_id IS NULL OR (quantity_issued = 1 AND quantity_returned IN (0,1))),
    UNIQUE (id, department_id),
    UNIQUE (id, issue_id, department_id)
);
CREATE UNIQUE INDEX one_active_issue_per_asset_uq ON issue_lines(asset_id)
  WHERE asset_id IS NOT NULL AND quantity_returned < quantity_issued;
CREATE INDEX issue_lines_due_date_idx ON issue_lines (department_id, due_date) WHERE quantity_returned < quantity_issued;
CREATE INDEX issues_student_idx ON issues (department_id, student_id, created_at DESC);

CREATE TABLE returns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    return_date DATE NOT NULL DEFAULT CURRENT_DATE,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    received_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    notes VARCHAR(1000),
    FOREIGN KEY (issue_id, department_id) REFERENCES issues(id, department_id) ON DELETE RESTRICT,
    UNIQUE (id, department_id),
    UNIQUE (id, issue_id, department_id)
);
CREATE TABLE return_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id BIGINT NOT NULL,
    issue_id BIGINT NOT NULL,
    issue_line_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    quantity_returned INTEGER NOT NULL CHECK (quantity_returned > 0),
    condition_on_return VARCHAR(20) NOT NULL CHECK (condition_on_return IN ('GOOD','FAIR','DAMAGED','MAINTENANCE')),
    notes VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (return_id, issue_id, department_id) REFERENCES returns(id, issue_id, department_id) ON DELETE RESTRICT,
    FOREIGN KEY (issue_line_id, issue_id, department_id) REFERENCES issue_lines(id, issue_id, department_id) ON DELETE RESTRICT
);

CREATE TABLE renewal_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_line_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
    requested_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    request_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
    old_due_date DATE NOT NULL,
    revised_due_date DATE,
    decided_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    decided_at TIMESTAMPTZ,
    remarks VARCHAR(1000),
    FOREIGN KEY (issue_line_id, department_id) REFERENCES issue_lines(id, department_id) ON DELETE RESTRICT,
    CHECK (
      (status = 'PENDING' AND revised_due_date IS NULL AND decided_by IS NULL AND decided_at IS NULL)
      OR (status = 'APPROVED' AND revised_due_date = old_due_date + 15 AND decided_by IS NOT NULL AND decided_at IS NOT NULL)
      OR (status = 'REJECTED' AND revised_due_date IS NULL AND decided_by IS NOT NULL AND decided_at IS NOT NULL AND char_length(btrim(COALESCE(remarks,''))) > 0)
    )
);
CREATE UNIQUE INDEX one_pending_renewal_per_issue_line_uq ON renewal_requests(issue_line_id) WHERE status='PENDING';
CREATE INDEX renewal_requests_department_status_idx ON renewal_requests(department_id,status,requested_at DESC);

CREATE TABLE stock_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL,
    inventory_item_id BIGINT NOT NULL,
    asset_id BIGINT,
    transaction_type VARCHAR(24) NOT NULL CHECK (transaction_type IN ('OPENING_BALANCE','ASSET_REGISTERED','ISSUE','RETURN','DAMAGE','LOSS','MAINTENANCE','ADJUSTMENT','RETIREMENT','TRANSFER_IN','TRANSFER_OUT')),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    from_bucket VARCHAR(16) NOT NULL CHECK (from_bucket IN ('EXTERNAL','AVAILABLE','ISSUED','DAMAGED','LOST','MAINTENANCE','RETIRED')),
    to_bucket VARCHAR(16) NOT NULL CHECK (to_bucket IN ('EXTERNAL','AVAILABLE','ISSUED','DAMAGED','LOST','MAINTENANCE','RETIRED')),
    reason VARCHAR(1000) NOT NULL CHECK (char_length(btrim(reason)) BETWEEN 3 AND 1000),
    performed_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    issue_id BIGINT,
    return_id BIGINT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (inventory_item_id, department_id) REFERENCES inventory_items(id, department_id) ON DELETE RESTRICT,
    FOREIGN KEY (asset_id, department_id, inventory_item_id) REFERENCES assets(id, department_id, inventory_item_id) ON DELETE RESTRICT,
    FOREIGN KEY (issue_id, department_id) REFERENCES issues(id, department_id) ON DELETE RESTRICT,
    FOREIGN KEY (return_id, department_id) REFERENCES returns(id, department_id) ON DELETE RESTRICT
);
CREATE INDEX stock_transactions_department_time_idx ON stock_transactions (department_id, occurred_at DESC);
CREATE INDEX stock_transactions_item_time_idx ON stock_transactions (inventory_item_id, occurred_at DESC);

